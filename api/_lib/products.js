/* =====================================================================
   AI 해석을 '새로 만들 수 있는' 횟수
   ---------------------------------------------------------------------
   AI 해석은 한 번 만들 때마다 실제로 돈이 나간다. 그런데 이용권은 브라우저 단위라
   프로필을 여러 개 만들면 한 번 결제로 몇 번이든 만들 수 있었다. 그대로 두면
   받은 값보다 원가를 더 쓰는 일이 생긴다.

   ★ '다시 보기'는 횟수를 쓰지 않는다. 한 번 만든 해석은 서버에 저장해 두고 그대로 내어준다.
     그래서 산 사람이 손해 볼 일은 없다 — 같은 사주를 백 번 열어도 1회다.
   ★ 만들다 실패한 것도 세지 않는다. 실패는 우리 잘못이지 이용자가 쓴 횟수가 아니다.
   ★ 이 숫자는 화면과 약관에도 같이 적어야 한다. 서버에서만 막고 말하지 않으면
     "왜 안 되냐"는 문의가 되고, 미리 알리지 않은 제한은 분쟁거리가 된다.
===================================================================== */
/* ★ 2026-09-04 — pass를 10에서 2로 내렸다. 기간이 7일에서 1년으로 늘었기 때문이다.
   2편인 이유(대표님 결정): 1편이면 내 것 하나로 끝이라 남의 사주를 봐드릴 수가 없다.
   프로필을 더 만들어도 "횟수를 다 쓰셨어요"에서 막힌다 — 화면은 열려 있는데 글이 안 나오는,
   잠긴 것보다 나쁜 상태가 된다. 2편이면 나 + 한 사람이고, 원가는 최대 6편 × 약 160원 = 960원이다.
   기간과 편수는 한 쌍이다 — 한쪽만 바꾸면 원가가 매출을 넘어선다(위 premium_pass 주석).
   ★ 이 숫자는 fortune.html의 AI_QUOTA와도 한 쌍이다. 화면이 적는 말과 서버가 막는 값이
     갈리면 화면이 거짓말을 한다. */
/* ★ 2026-09-07 대표님 지시 — 이 숫자는 이제 **상한이 아니라 '결제 한 건이 주는 편수'**다.
   ---------------------------------------------------------------------
   "1쌍에 990원이고 2쌍은 990원*2 이런식으로 추가 과금해야지"

   실제 판정은 hasAiAccess(aiprompt.js)가 한다:
       만들 수 있는 편수 = (이용권이 살아 있으면 pass) + (그 상품을 산 횟수)
   그래서 궁합 990원을 두 번 사면 두 쌍, 사주 1,900원을 두 번 사면 두 편이다.
   상품을 가리지 않고 같은 규칙이다.
   ★ once를 2 이상으로 올리지 마라. 한 번 결제에 몇 편을 줄지는 이 숫자이고,
     '더 사면 더'는 결제 건수가 맡는다. 둘을 섞으면 원가가 두 배로 뛴다.
   ★ 이 숫자는 fortune.html의 AI_QUOTA와도 한 쌍이다. 화면이 적는 말과 서버가 막는 값이
     갈리면 화면이 거짓말을 한다. */
export const AI_QUOTA = { once: 1, pass: 2 };

export function aiQuotaOf(kind) {
  return kind === 'pass' ? AI_QUOTA.pass : AI_QUOTA.once;
}

