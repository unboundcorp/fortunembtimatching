/* =====================================================================
   궁합 화면 안내가 실제 계산과 어긋나지 않는가 (빠른 층)
   ---------------------------------------------------------------------
   2026-09-09 — 팔기 전 마지막 점검에서 잡은 것입니다.

   결과 화면이 **"상대방 화면에는 1~2점 다르게 나올 수 있어요"** 라고 적고 있었습니다.
   그런데 2026-09-05에 상생을 양방향 92로 맞춘 뒤로 점수는 어느 쪽에서 보든 같습니다
   (실측: 무작위 4,005쌍 양방향 계산 · 다른 쌍 0건). FAQ 는 '같아요'라고 적고 있어서
   **한 서비스 안에서 두 화면이 서로 다른 말을 하고 있었습니다.**
   상생은 전체 쌍의 약 40%라 손님 열 분 중 넉 분이 보던 문장입니다.

   ★ 계산이 맞는지는 `calc.cjs` 가 봅니다. 여기서 보는 것은 **글이 계산을 따라왔는가** 입니다.
     계산을 고치고 글을 안 고치는 것이 이 프로젝트에서 되풀이된 실수입니다.
===================================================================== */
const fs = require('fs');
const path = require('path');
const { ROOT, reporter } = require('../_lib.cjs');

const R = reporter('궁합 안내 글');
const html = fs.readFileSync(path.join(ROOT, 'fortune.html'), 'utf8');

R.head('── 점수 대칭과 안내가 맞는가');

/* 옛 문장이 되살아나면 안 된다 */
R.note(!/1~2점 다르게 나올 수 있어요/.test(html),
       "'상대방 화면에는 1~2점 다르게' 라는 낡은 안내가 없다");
R.note(!/사주 점수가 조금 달라진다/.test(html),
       "'보는 사람에 따라 사주 점수가 달라진다'는 낡은 설명이 없다");

/* 지금 문장은 '설명은 반대, 점수는 같다' 여야 한다 */
R.note(/상대방 화면에는 설명이 반대로 적혀요\. 점수는 두 분이 같아요/.test(html),
       '지금 안내가 「설명은 반대 · 점수는 같음」을 말한다');

/* FAQ 와 같은 말을 하는가 */
R.note(/누가 먼저 보든 점수가 같나요\?/.test(html) &&
       /점수는 두 분 공통값으로 봐요/.test(html),
       'FAQ 도 같은 말을 하고 있다');

/* 점수를 실제로 대칭으로 만든 자리가 그대로인가 —
   상생이 방향마다 다른 값으로 되돌아가면 위 문장이 다시 거짓이 된다.
   ★ 값을 여기 베껴 적지 않고, '두 방향이 같은 상수를 쓰는가'만 본다. */
const m = /상생[\s\S]{0,400}?92/.test(html);
R.note(m, '상생 점수가 양방향 같은 값(92)으로 적혀 있다');

R.done();
