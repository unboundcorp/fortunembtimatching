#!/usr/bin/env node
/* =====================================================================
   결제 문구에 '사다' 가 되살아나지 않는가 (빠른 층)
   ---------------------------------------------------------------------
   2026-09-11 대표님 지시 — "사다라는 표현 바꿔 / 사다 → 구매하다 · 사면 → 구매하면 /
   ~해요체지만 용어는 격식있게 가자".

   ★ 이 검사의 진짜 목적은 **일괄 치환 사고를 막는 것**입니다. 이 서비스에는 글자만 같은
     말이 잔뜩 있습니다 — 사주 · 사신(신살) · 사시(巳時) · 사실(고지) · 사는 편이에요(살다).
     기계로 '사'를 바꾸면 사주팔자가 통째로 망가집니다. 그래서 ②절이 그것들이 그대로
     살아 있는지를 함께 봅니다.
   ★ 문구를 셀 때는 **주석을 걷고** 셉니다 — 안 걷으면 이 설명 주석이 제 검사에 걸립니다
     (이 프로젝트에서 되풀이된 함정입니다).
===================================================================== */
const fs = require('fs');
const path = require('path');
const L = require('../_lib.cjs');

const ROOT = path.join(__dirname, '..', '..');
const strip = (t) => t.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');
const code = strip(fs.readFileSync(path.join(ROOT, 'fortune.html'), 'utf8'));

(async () => {
  const R = L.reporter('결제 문구 — 구매하다');

  R.head('① 옛 표현이 되살아나지 않았는가');
  [['셋을 사면',        /셋을 사면/],
   ['이용권을 사면',    /이용권을 사면/],
   ['하나씩 다 사면',   /하나씩 다 사면/],
   ['한 번 사시면',     /한 번 사시면/],
   ['사시면 / 사신 분', /사시면|사신 분/],
  ].forEach(function (p) {
    R.note(!p[1].test(code), '화면 글에 「' + p[0] + '」 이 없다');
  });

  R.head('② 지금 문구가 실제로 들어 있는가');
  [['따로 셋을 구매하면',      /따로 셋을 구매하면/],
   ['전체 이용권을 구매하면',  /전체 이용권을 구매하면/],
   ['하나씩 다 구매하면',      /하나씩 다 구매하면/],
   ['한 번 구매하면 해당 년도', /한 번 구매하면 해당 년도 사주는/],
  ].forEach(function (p) {
    R.note(p[1].test(code), '「' + p[0] + '」 이 있다');
  });

  R.head('③ 글자만 같은 말을 함께 바꾸지 않았는가 (일괄 치환 사고 방지)');
  [['사주팔자',              /사주팔자/],
   ['사신 (신살·육합 표기)',  /·사신/],
   ['사시 (巳時)',           /'사시\(/],
   ['걱정을 사서 하거나',     /걱정을 사서/],
  ].forEach(function (p) {
    R.note(p[1].test(code), p[0] + ' 는 그대로다');
  });

  R.done();
})();
